/**
 * test-generator — Darwin skill: generate a test file stub for a given source file.
 * ADR-009 mechanical rule engine (LLM-free). Options: framework, module, minCases, includeNegative.
 */
export const testGenerator = {
  name: 'test-generator',
  description: 'Generate a test file stub for a given source file (v3+ P1 catalog item).',
  triggers: ['test', 'generate test', 'testgen', 'test-gen', '生成测试', '写测试'],
  systemPromptHint:
    'User wants a test stub. Use node:test + assert; cover contract, error paths, edge cases; never skip the TypeError guard.',
  async execute(input, context = {}) {
    const { sourcePath, sourceContent } = resolveSource(input, context);
    if (!sourcePath && sourceContent !== '' && !sourceContent) {
      return blankTest();
    }
    const opts = context && typeof context.options === 'object' ? context.options : {};
    const imports = extractExports(sourceContent);
    const ctxSp = context && typeof context.sourcePath === 'string' ? context.sourcePath : null;
    const stem = (s) => (s.split('/').pop() || 'mod').replace(/\.[^.]+$/, '') || 'mod';
    const b = ctxSp ? stem(ctxSp) : imports[0] ? imports[0].name.toLowerCase() : stem(sourcePath);
    return buildTest(b, imports, opts);
  },
};
function resolveSource(input, context = {}) {
  const ctxSc =
    typeof context.sourceContent === 'string' && context.sourceContent.length > 0
      ? context.sourceContent
      : null;
  const ctxSp = typeof context.sourcePath === 'string' ? context.sourcePath : null;
  if (ctxSc) {
    return { sourcePath: ctxSp || input || '<input>', sourceContent: ctxSc };
  }
  if (typeof input !== 'string' || input.length === 0) {
    return { sourcePath: null, sourceContent: null };
  }
  const isPath =
    input.length < 256 &&
    !/[\s;]/.test(input) &&
    (/^[./A-Za-z0-9_-]+\.[A-Za-z0-9]+$/.test(input) ||
      (input.includes('/') && !input.includes('//')));
  if (isPath) {
    return { sourcePath: input, sourceContent: '' };
  }
  return { sourcePath: ctxSp || '<input>', sourceContent: input };
}
function extractExports(src) {
  const kinds = [
    ['const', /^export\s+const\s+([A-Za-z_$][\w$]*)/gm],
    ['function', /^export\s+function\s+([A-Za-z_$][\w$]*)/gm],
    ['class', /^export\s+class\s+([A-Za-z_$][\w$]*)/gm],
  ];
  const out = [];
  for (const [kind, re] of kinds) {
    for (const m of src.matchAll(re)) {
      out.push({ name: m[1], kind });
    }
  }
  return out;
}
function buildTest(b, imports, opts) {
  const fw = opts.framework === 'jest' ? 'jest' : 'node:test';
  const mod = opts.module === 'cjs' ? 'cjs' : 'esm';
  const n = Number.isInteger(opts.minCases) && opts.minCases > 0 ? opts.minCases : 5;
  const neg = opts.includeNegative === false ? false : true;
  const names = imports.map((i) => i.name).join(', ');
  const output = renderStub({ b, names, fw, mod, n, neg });
  return {
    output,
    suggested: {
      testPath: `tests/${b}.test.js`,
      framework: fw,
      module: mod,
      imports,
      cases: n,
      stubs: n,
    },
    stats: { cases: n, lines: output.split('\n').length, imports: imports.length, stubs: n },
  };
}
function renderStub({ b, names, fw, mod, n, neg }) {
  const cjs = mod === 'cjs';
  const L = [
    `/**`,
    ` * ${b} tests — generated by test-generator skill (v3+ P1 stub).`,
    ` * Run: \`node --test tests/${b}.test.js\` | Framework: ${fw} | Module: ${mod}`,
    ` */`,
    `// TODO(p2): wire to provider.chat() for richer test generation`,
  ];
  if (cjs) {
    L.push(
      `const { test, describe } = require('node:test');`,
      `const assert = require('node:assert/strict');`,
      names ? `const { ${names} } = require('./${b}.js');` : `// const MOD = require('./${b}.js');`,
    );
  } else {
    L.push(
      `import { test, describe } from 'node:test';`,
      `import assert from 'node:assert/strict';`,
      names ? `import { ${names} } from './${b}.js';` : `// import { <exports> } from './${b}.js';`,
    );
  }
  const positiveCount = neg ? Math.max(0, n - 1) : n;
  const cases = [
    'happy path',
    'edge: empty',
    'edge: large',
    'edge: special chars',
    'returns shape',
    'preserves type',
    'handles unicode',
    'stable id',
    'clones input',
    'inverts negative',
  ];
  L.push(`describe('${b} — execute()', () => {`);
  for (let i = 0; i < positiveCount && i < cases.length; i++) {
    L.push(
      `  test('${cases[i]}', async () => {`,
      `    // const r = await MOD.execute(/* valid input */);`,
      `  });`,
    );
  }
  for (let i = cases.length; i < positiveCount; i++) {
    L.push(
      `  test('case ${i + 1}', async () => {`,
      `    // const r = await MOD.execute(/* valid input */);`,
      `  });`,
    );
  }
  L.push(`});`);
  if (neg) {
    L.push(
      `describe('${b} — error paths', () => {`,
      `  test('throws TypeError on bad input', async () => {`,
      `    // await assert.rejects(() => MOD.execute(/* bad input */), TypeError);`,
      `  });`,
      `});`,
    );
  }
  if (fw === 'jest') {
    L.push(
      '// NOTE: framework=jest requested; stub still emits node:test imports. Wire @jest/globals in TODO(p2).',
    );
  }
  return L.join('\n');
}
function blankTest() {
  const output = `/**\n * test-generator: empty input, no source provided.\n */\n// TODO(p2): wire to provider.chat()`;
  return {
    output,
    suggested: {
      testPath: 'test.test.js',
      framework: 'node:test',
      module: 'esm',
      imports: [],
      cases: 0,
      stubs: 0,
    },
    stats: { cases: 0, lines: 0, imports: 0, stubs: 0 },
  };
}
export default testGenerator;
